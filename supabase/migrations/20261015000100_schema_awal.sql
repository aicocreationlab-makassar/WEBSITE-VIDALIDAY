-- ---------------------------------------------------------------------
--  1. Admin
--     Hanya user yang terdaftar di tabel ini yang boleh mengubah data.
--     (User "authenticated" biasa TIDAK otomatis jadi admin.)
-- ---------------------------------------------------------------------
create table if not exists public.admins (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admins a where a.user_id = auth.uid()
  );
$$;


-- ---------------------------------------------------------------------
--  2. Tabel konten (1:1 dengan migration Laravel)
-- ---------------------------------------------------------------------
create table if not exists public.locations (
  id          bigint generated by default as identity primary key,
  slug        text not null unique,
  name        text not null,
  tagline     text,
  description text,
  address     text,
  gmaps_url   text,
  hero_image  text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.units (
  id                bigint generated by default as identity primary key,
  location_id       bigint not null references public.locations (id) on delete cascade,
  name              text not null,
  slug              text not null unique,
  room_type         text not null,
  max_guests        integer not null default 2,
  normal_price      numeric(12, 2) not null default 0,   -- harga coret
  promo_price       numeric(12, 2) not null default 0,   -- harga aktif
  promo_badge       text,
  is_promo_active   boolean not null default true,
  rental_period     text not null default 'Harian',
  description       text,
  facilities_list   jsonb not null default '[]'::jsonb,  -- ["AC", "Smart TV", ...]
  youtube_video_url text,
  main_image        text,                                -- path di bucket "media" atau URL penuh
  gallery_images    jsonb not null default '[]'::jsonb,  -- array path
  is_featured       boolean not null default false,
  is_available      boolean not null default true,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create table if not exists public.facilities (
  id          bigint generated by default as identity primary key,
  location_id bigint not null references public.locations (id) on delete cascade,
  name        text not null,
  icon        text,
  description text,
  image       text,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.landmarks (
  id            bigint generated by default as identity primary key,
  location_id   bigint not null references public.locations (id) on delete cascade,
  name          text not null,
  distance_time text not null,
  notes         text,
  sort_order    integer not null default 0,
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table if not exists public.faqs (
  id         bigint generated by default as identity primary key,
  question   text not null,
  answer     text not null,
  badge      text,
  sort_order integer not null default 0,
  is_active  boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.settings (
  id         bigint generated by default as identity primary key,
  key        text not null unique,
  value      text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists units_location_id_idx      on public.units (location_id);
create index if not exists facilities_location_id_idx on public.facilities (location_id);
create index if not exists landmarks_location_id_idx  on public.landmarks (location_id);


-- ---------------------------------------------------------------------
--  3. Hak akses dasar (RLS tetap yang menentukan baris mana yang boleh)
-- ---------------------------------------------------------------------
grant usage on schema public to anon, authenticated, service_role;

grant select on public.locations, public.units, public.facilities,
                public.landmarks, public.faqs, public.settings
  to anon, authenticated;

grant insert, update, delete on public.locations, public.units, public.facilities,
                                public.landmarks, public.faqs, public.settings
  to authenticated;

grant select on public.admins to authenticated;

grant all on public.locations, public.units, public.facilities,
             public.landmarks, public.faqs, public.settings, public.admins
  to service_role;

grant usage, select on all sequences in schema public to authenticated, service_role;


-- ---------------------------------------------------------------------
--  4. Row Level Security
--     Publik: hanya boleh BACA. Tulis: hanya admin.
--     Tanpa RLS, siapa pun bisa mengubah harga lewat API karena
--     publishable/anon key terlihat di browser.
-- ---------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array['locations', 'units', 'facilities', 'landmarks', 'faqs', 'settings'] loop
    execute format('alter table public.%I enable row level security', t);

    execute format('drop policy if exists "admin write" on public.%I', t);
    execute format(
      'create policy "admin write" on public.%I for all to authenticated
         using (public.is_admin()) with check (public.is_admin())', t);

    execute format('drop policy if exists "public read" on public.%I', t);
  end loop;
end
$$;

-- Lokasi, unit, fasilitas, settings: semua boleh dibaca publik
create policy "public read" on public.locations  for select to anon, authenticated using (true);
create policy "public read" on public.units      for select to anon, authenticated using (true);
create policy "public read" on public.facilities for select to anon, authenticated using (true);
create policy "public read" on public.settings   for select to anon, authenticated using (true);

-- FAQ & landmark: publik hanya melihat yang aktif, admin melihat semua
create policy "public read" on public.faqs      for select to anon, authenticated using (is_active or public.is_admin());
create policy "public read" on public.landmarks for select to anon, authenticated using (is_active or public.is_admin());

-- Tabel admins: user hanya bisa melihat baris miliknya sendiri
alter table public.admins enable row level security;
drop policy if exists "read own admin row" on public.admins;
create policy "read own admin row" on public.admins
  for select to authenticated using (user_id = auth.uid());


-- ---------------------------------------------------------------------
--  5. Storage: bucket "media" (pengganti storage/app/public Laravel)
--     Struktur folder sama: units/..., facilities/..., settings/...
--     Bucket publik → foto bisa diakses via URL tanpa login.
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('media', 'media', true)
on conflict (id) do update set public = excluded.public;

drop policy if exists "media: admin read"   on storage.objects;
drop policy if exists "media: admin insert" on storage.objects;
drop policy if exists "media: admin update" on storage.objects;
drop policy if exists "media: admin delete" on storage.objects;

create policy "media: admin read" on storage.objects
  for select to authenticated
  using (bucket_id = 'media' and public.is_admin());

create policy "media: admin insert" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'media' and public.is_admin());

create policy "media: admin update" on storage.objects
  for update to authenticated
  using (bucket_id = 'media' and public.is_admin())
  with check (bucket_id = 'media' and public.is_admin());

create policy "media: admin delete" on storage.objects
  for delete to authenticated
  using (bucket_id = 'media' and public.is_admin());


-- ---------------------------------------------------------------------
--  6. Sinkronkan sequence id setelah import
--     Karena id lama dipertahankan, sequence harus dimajukan supaya
--     data baru dari admin panel tidak bentrok id. Dipanggil otomatis
--     oleh script migrasi; hanya bisa dijalankan service role.
-- ---------------------------------------------------------------------
create or replace function public.sync_id_sequences()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  t text;
begin
  foreach t in array array['locations', 'units', 'facilities', 'landmarks', 'faqs', 'settings'] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from public.%I), 0) + 1, false)',
      'public.' || t, t
    );
  end loop;
end;
$$;

revoke execute on function public.sync_id_sequences() from public, anon, authenticated;
grant execute on function public.sync_id_sequences() to service_role;
