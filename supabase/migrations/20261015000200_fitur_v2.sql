-- ---------------------------------------------------------------------
--  8c. backfill_v2(): isi kolom/tabel baru dari data lama.
--      Aman diulang. Jalankan lagi setelah migrasi data final:
--        select public.backfill_v2();
-- ---------------------------------------------------------------------
create or replace function public.backfill_v2()
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  r              record;
  v_type_id      bigint;
  v_cat          text;
  v_slug         text;
  v_units_mapped integer := 0;
  v_links        integer := 0;
begin
  -- a. Nama singkat, area, urutan untuk 2 apartemen awal (hanya jika kosong)
  update public.locations
     set short_name = 'Vida View', area = coalesce(area, 'Panakkukang'),
         sort_order = case when sort_order = 0 then 1 else sort_order end
   where slug = 'vida-view' and short_name is null;
  update public.locations
     set short_name = 'Delft CPI', area = coalesce(area, 'Center Point of Indonesia'),
         sort_order = case when sort_order = 0 then 2 else sort_order end
   where slug = 'delft-cpi' and short_name is null;
  update public.locations set short_name = name where short_name is null;

  -- b. Tipe kamar awal sesuai permintaan klien.
  --    Hanya untuk apartemen yang belum punya tipe sama sekali, supaya tipe
  --    yang sudah dihapus/diubah admin tidak muncul lagi saat backfill diulang.
  insert into public.room_types (location_id, name, slug, category, default_max_guests, sort_order)
  select l.id, t.name, t.slug, t.category, t.guests, t.ord
    from public.locations l
    join (values
      ('vida-view', 'Studio',             'studio',           'studio', 3,  1),
      ('vida-view', 'Studio Plus',        'studio-plus',      'studio', 5,  2),
      ('vida-view', '2 Bedroom',          '2-bedroom',        '2br',    5,  3),
      ('vida-view', '2 Bedroom Corner',   '2-bedroom-corner', '2br',    7,  4),
      ('vida-view', '3 Bedroom',          '3-bedroom',        '3br',    10, 5),
      ('delft-cpi', 'Studio',             'studio',           'studio', 3,  1),
      ('delft-cpi', 'Studio Corner',      'studio-corner',    'studio', 5,  2),
      ('delft-cpi', '2 Bedroom / Corner', '2-bedroom-corner', '2br',    5,  3),
      ('delft-cpi', '3 Bedroom',          '3-bedroom',        '3br',    10, 4)
    ) as t(loc_slug, name, slug, category, guests, ord) on t.loc_slug = l.slug
   where not exists (select 1 from public.room_types rt where rt.location_id = l.id)
  on conflict (location_id, slug) do nothing;

  -- c. Hubungkan unit lama ke tipe kamar
  for r in
    select u.id, u.location_id, coalesce(nullif(btrim(u.room_type), ''), 'Lainnya') as type_name
      from public.units u
     where u.room_type_id is null
  loop
    v_cat := case
      when r.type_name ~* '^\s*studio'          then 'studio'
      when r.type_name ~* '^\s*1\s*-?\s*(br|bed)' then '1br'
      when r.type_name ~* '^\s*2\s*-?\s*(br|bed)' then '2br'
      when r.type_name ~* '^\s*3\s*-?\s*(br|bed)' then '3br'
      else 'other'
    end;

    -- 1) nama sama (abaikan huruf besar, spasi, simbol)
    select rt.id into v_type_id
      from public.room_types rt
     where rt.location_id = r.location_id
       and regexp_replace(lower(rt.name), '[^a-z0-9]', '', 'g')
         = regexp_replace(lower(r.type_name), '[^a-z0-9]', '', 'g')
     order by rt.id
     limit 1;

    -- 2) kategori sama, dan di apartemen itu hanya ada satu tipe dengan kategori tsb
    if v_type_id is null and v_cat <> 'other' then
      select min(rt.id) into v_type_id
        from public.room_types rt
       where rt.location_id = r.location_id and rt.category = v_cat
      having count(*) = 1;
    end if;

    -- 3) belum ada: buat tipe baru dari teks lama
    if v_type_id is null then
      v_slug := coalesce(nullif(btrim(regexp_replace(lower(r.type_name), '[^a-z0-9]+', '-', 'g'), '-'), ''), 'tipe');
      insert into public.room_types (location_id, name, slug, category, sort_order)
      values (r.location_id, r.type_name, v_slug, v_cat, 99)
      on conflict (location_id, slug) do update set slug = excluded.slug
      returning id into v_type_id;
    end if;

    update public.units set room_type_id = v_type_id where id = r.id;
    v_units_mapped := v_units_mapped + 1;
  end loop;

  -- d. Tebak lantai, tower, dan view dari deskripsi lama (hanya jika kosong).
  --    Hasilnya tebakan: admin tetap perlu mengecek.
  update public.units
     set floor_number = (regexp_match(description, 'lantai\s*(\d{1,2})', 'i'))[1]::integer
   where floor_number is null and description ~* 'lantai\s*\d{1,2}';

  update public.units
     set tower = initcap((regexp_match(description, 'tower\s+([a-z]+)', 'i'))[1])
   where tower is null and description ~* 'tower\s+[a-z]+';

  -- catatan: '\s+?' sengaja non-greedy; di Postgres greediness seluruh regex
  -- mengikuti quantifier pertama.
  update public.units
     set view_type = upper(left(m.v, 1)) || substr(m.v, 2)
    from (
      select u.id,
             btrim((regexp_match(u.description,
               'view\s+?(.*?)(?:\s*,\s*(?:lantai|tower)\M|\s+(?:lantai|tower|yang|berada)\M|$)', 'i'))[1], ' ,.') as v
        from public.units u
       where u.view_type is null and u.description ~* 'view\s+\S'
    ) m
   where public.units.id = m.id and coalesce(m.v, '') <> '';

  -- e. Fasilitas kamar: isi master awal (hanya kalau tabel masih kosong)
  if not exists (select 1 from public.amenities) then
    insert into public.amenities (name, icon, sort_order) values
      ('AC', 'air-vent', 1), ('WiFi', 'wifi', 2), ('Smart TV', 'tv', 3),
      ('Smart TV 43 inci', 'tv', 4), ('Netflix', 'clapperboard', 5),
      ('Water Heater', 'shower-head', 6), ('Kitchen Set', 'cooking-pot', 7),
      ('Queen Bed', 'bed-double', 8), ('Balkon', 'fence', 9),
      ('Kulkas', 'refrigerator', 20), ('Mesin Cuci', 'washing-machine', 21),
      ('Microwave', 'microwave', 22), ('Sofa', 'sofa', 23),
      ('Meja Kerja', 'laptop', 24), ('Perlengkapan Mandi', 'bath', 25),
      ('Setrika', 'shirt', 26), ('Dispenser Air', 'glass-water', 27);
  end if;

  -- f. Hubungkan unit ke fasilitas dari kolom lama facilities_list.
  --    Hanya untuk unit yang belum punya fasilitas di tabel baru.
  drop table if exists pg_temp.v2_items;
  create temp table v2_items as
  with alias(norm, canonical) as (values
    ('ac', 'AC'), ('acdingin', 'AC'), ('airconditioner', 'AC'),
    ('wifi', 'WiFi'), ('freewifi', 'WiFi'), ('internet', 'WiFi'),
    ('tv', 'Smart TV'), ('smarttv', 'Smart TV'),
    ('smarttv43', 'Smart TV 43 inci'), ('smarttv43inch', 'Smart TV 43 inci'),
    ('smarttv43inci', 'Smart TV 43 inci'),
    ('netflix', 'Netflix'),
    ('waterheater', 'Water Heater'), ('airpanas', 'Water Heater'),
    ('kitchenset', 'Kitchen Set'), ('dapur', 'Kitchen Set'),
    ('queenbed', 'Queen Bed'),
    ('balkon', 'Balkon'), ('balcony', 'Balkon')
  ),
  items as (
    select u.id as unit_id, btrim(x.value) as raw
      from public.units u
     cross join lateral jsonb_array_elements_text(
       case when jsonb_typeof(u.facilities_list) = 'array' then u.facilities_list else '[]'::jsonb end
     ) as x(value)
     where btrim(x.value) <> ''
       and not exists (select 1 from public.unit_amenities ua where ua.unit_id = u.id)
  )
  select distinct i.unit_id, coalesce(a.canonical, i.raw) as amenity_name
    from items i
    left join alias a on a.norm = regexp_replace(lower(i.raw), '[^a-z0-9]', '', 'g');

  insert into public.amenities (name, icon, sort_order)
  select distinct on (lower(amenity_name)) amenity_name, 'check', 50
    from pg_temp.v2_items
   order by lower(amenity_name), amenity_name
  on conflict ((lower(name))) do nothing;

  insert into public.unit_amenities (unit_id, amenity_id)
  select distinct v.unit_id, am.id
    from pg_temp.v2_items v
    join public.amenities am on lower(am.name) = lower(v.amenity_name)
  on conflict do nothing;
  get diagnostics v_links = row_count;

  drop table if exists pg_temp.v2_items;

  return jsonb_build_object(
    'units_mapped_to_room_type', v_units_mapped,
    'amenity_links_created', v_links,
    'units_without_room_type', (select count(*) from public.units where room_type_id is null)
  );
end;
$$;

