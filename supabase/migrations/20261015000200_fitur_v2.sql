create table if not exists public.room_types (
  id                 bigint generated by default as identity primary key,
  location_id        bigint not null references public.locations (id) on delete cascade,
  name               text not null,
  slug               text not null,
  category           text not null default 'other'
                     check (category in ('studio', '1br', '2br', '3br', 'other')),
  default_max_guests integer check (default_max_guests between 1 and 30),
  sort_order         integer not null default 0,
  is_active          boolean not null default true,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  unique (location_id, slug)
);

create index if not exists room_types_location_idx on public.room_types (location_id, sort_order);


