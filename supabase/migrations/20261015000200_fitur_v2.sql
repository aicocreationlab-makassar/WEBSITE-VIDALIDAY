set search_path = ''
as $$
declare
  t text;
begin
  foreach t in array array['locations', 'units', 'facilities', 'landmarks', 'faqs', 'settings',
                           'room_types', 'amenities'] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from public.%I), 0) + 1, false)',
      'public.' || t, t
    );
  end loop;
